/* R34 Reading draft bank validator for the complete 5 x 4 x 6 matrix.
 * Two individually written references (EN/B1,B2) and 118 UNREVIEWED
 * mechanically generated drafts must never be treated as equal quality.
 * A static GitHub site cannot protect answer keys or verify pupils.
 */
(function(root){
 'use strict';
 const KIND='LSH_INDEPENDENT_READING_TEST_DRAFT_R32_V1';
 const STATUS='DRAFT_PENDING_TEACHER_CONTENT_APPROVAL';
 const LANGUAGES=Object.freeze(['en','es','de','fr']);
 const LEVELS=Object.freeze(['A1','A2','B1','B2','C1','C2']);
 const TOPICS=Object.freeze(['rl-asteroids','rl-can-mistakes','rl-plastic-ocean','rl-email-friend','rl-instant-messages']);
 const AUTHOR=Object.freeze({
  'rl-can-mistakes:en:B1':{prefix:'r33',audit:'R33-CONTENT-AUDIT-1',title:'The Problem with Being Good at Everything'},
  'rl-can-mistakes:en:B2':{prefix:'r32',audit:'R32-CONTENT-AUDIT-1',title:'When Feedback Feels Like Failure'}
 });
 const text=s=>typeof s==='string'&&s.trim().length>0;
 const norm=s=>s.normalize('NFKC').toLowerCase().replace(/\s+/g,' ').trim();
 function check(ok,msg){if(!ok)throw new Error(msg)}
 function validate(bank,practice,expectedSourceHash,expectedSelection){
  check(bank&&typeof bank==='object'&&!Array.isArray(bank)&&bank.kind===KIND,
   'Invalid pilot test-bank format');
  check(bank.status===STATUS&&bank.published===false,
   'R32 content cannot be published without teacher approval');
  check(TOPICS.includes(bank.topic)&&LANGUAGES.includes(bank.language)&&
   LEVELS.includes(bank.level),'Unsupported independent test variant');
  if(expectedSelection){
   check(expectedSelection.topic===bank.topic&&
    expectedSelection.lang===bank.language&&expectedSelection.level===bank.level,
    'Wrong topic/language/level bank for the requested assessment');
  }
  const author=AUTHOR[[bank.topic,bank.language,bank.level].join(':')];
  const generated=!author;
  if(author){
   check(bank.auditRevision===author.audit,
    'Independent pedagogy audit not completed');
   check(bank.editorialStatus===undefined||bank.editorialStatus==='AUTHORED_PENDING_REVIEW',
    'Unexpected author-review status');
  }else{
   check(bank.auditRevision==='R34-STRUCTURAL-DRAFT'&&
    bank.editorialStatus==='AUTO_GENERATED_NOT_PEDAGOGICALLY_VALIDATED',
    'Autogenerated assessment must stay explicitly unreviewed');
  }
  check(/^[a-f0-9]{64}$/.test(expectedSourceHash)&&
   bank.sourcePracticeContentHash===expectedSourceHash,'The practice source has changed');
  check(practice&&text(practice.title)&&
   (!author||practice.title===author.title)&&Array.isArray(practice.paragraphs)&&
   practice.paragraphs.length>=3&&Array.isArray(practice.questions),
   'Practice source does not match this bank level and passage');
  check(practice.questions.every(q=>typeof q.id==='string'&&
   q.id.startsWith(bank.language+'-'+bank.level.toLowerCase()+'-')),
   'Practice source does not match selected language and CEFR level');
  check(Array.isArray(bank.tabs)&&bank.tabs.length===3&&
   bank.tabs.every(t=>text(t.id)&&text(t.title)&&/^[a-z][a-z0-9-]+$/.test(t.id)),
   'Invalid pilot test sections');
  const ids=new Set(bank.tabs.map(t=>t.id));
  check(ids.size===bank.tabs.length,'Duplicate test section');
  check(Array.isArray(bank.questions)&&bank.questions.length===10,
   'Independent draft requires ten assessment questions');
  const stems=new Set(practice.questions.map(q=>norm(q.q)));
  const practiceIds=new Set(practice.questions.map(q=>q.id));
  const seen=new Set(),answerPositions=[0,0,0,0];
  for(const q of bank.questions){
   const prefix=author?author.prefix+'-en-'+bank.level.toLowerCase()+'-':
    'r34-'+bank.topic.slice(3)+'-'+bank.language+'-'+bank.level.toLowerCase()+'-';
   check(q&&text(q.id)&&q.id.startsWith(prefix)&&
    /^[a-z0-9-]+$/.test(q.id)&&!seen.has(q.id)&&!practiceIds.has(q.id),
    'Duplicate or reused question ID');
   seen.add(q.id);
   check(Number.isInteger(q.sourceParagraph)&&q.sourceParagraph>=1&&
    q.sourceParagraph<=practice.paragraphs.length,'Missing or invalid evidence paragraph');
   check(ids.has(q.tab)&&q.kind==='mc'&&text(q.q)&&q.q.length>=24&&
    !stems.has(norm(q.q)),'Test question must be distinct from practice');
   stems.add(norm(q.q));
   check(Array.isArray(q.choices)&&q.choices.length===4&&
    q.choices.every(c=>text(c)&&c.length>=10)&&
    new Set(q.choices.map(norm)).size===4,'Invalid or duplicated options');
   check(Number.isInteger(q.answer)&&q.answer>=0&&q.answer<4,'Invalid correct-answer index');
   answerPositions[q.answer]++;
   check(text(q.explanation)&&q.explanation.length>=(generated?12:30),
    'Missing evidence-based explanation');
   if(generated){
    check(q.generationMethod==='mechanical_evidence_location',
     'Incorrect generated draft marker');
    const correct=q.choices[q.answer].replace(/…$/,'').trim();
    check(correct.length>=10&&practice.paragraphs[q.sourceParagraph-1].includes(correct),
     'Generated key not grounded in cited paragraph');
   }
  }
  check(answerPositions.every(n=>n>=2&&n<=3),
   'Correct answer locations are unbalanced across four positions');
  check(typeof bank.scoreRule==='string'&&
   bank.scoreRule.startsWith('1 point per correct MC item'),'Unknown scoring method');
  return true;
 }
 function makeQaVariant(bank,practice,expectedSourceHash,selection){
  validate(bank,practice,expectedSourceHash,selection);
  return {
   title:practice.title+' — independent '+bank.language.toUpperCase()+'/'+bank.level+' test draft',
   paragraphs:practice.paragraphs.slice(),
   tabs:bank.tabs.map(t=>({...t})),
   questions:bank.questions.map(q=>({...q,choices:q.choices.slice()})),
   open:''
  };
 }
 const api=Object.freeze({KIND,STATUS,LANGUAGES,LEVELS,TOPICS,validate,makeQaVariant});
 if(typeof module!=='undefined'&&module.exports)module.exports=api;
 else root.LSHIndependentTestBank=api;
})(typeof window!=='undefined'?window:this);
